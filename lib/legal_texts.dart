/// Один документ: заголовок + разделы.
class LegalDocument {
  final String title;
  final List<LegalSection> sections;

  const LegalDocument({required this.title, required this.sections});
}

class LegalSection {
  final String heading;
  final String body;

  const LegalSection(this.heading, this.body);
}

